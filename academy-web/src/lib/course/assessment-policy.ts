/** ข้อความบอกผู้เรียนตรงๆ ว่าทำไมยังข้ามด้วยการพิสูจน์ไม่ได้ */
export const TEST_OUT_UNAVAILABLE_REASON =
  'บทนี้ยังไม่เปิดให้พิสูจน์เพื่อข้าม — กำลังเตรียมคลังข้อสำหรับการวัดผลอยู่'

/**
 * บทปกติผิดได้กี่ข้อถึงยังนับว่า `completed` (W0-3 · founder เปลี่ยนตัวเลขได้)
 *
 * เดิมบทปกติผ่านด้วย "ตอบครบ" เฉยๆ — ตอบผิดทุกข้อก็ได้ `completed` (F2) ·
 * เกณฑ์ "ผิดไม่เกิน 1" ทดสอบได้ตรงๆ และไม่ทิ้งท่าที "ตอบผิดไม่ใช่บทลงโทษ"
 * (retry ยังไม่จำกัด)
 */
export const LEARN_MODE_ALLOWED_WRONG = 1

/**
 * บทปกติผ่านหรือยัง — **จุดเดียวที่ตัดสิน**
 *
 * ⚠️ เกณฑ์ "ผิดไม่เกิน 1" อย่างเดียวใช้ไม่ได้ เพราะคอร์สจริงมีบทที่มี checkpoint
 * 1–2 ข้อ ซึ่งจะกลายเป็น "ผ่านโดยไม่ต้องตอบถูกสักข้อ" — เป็นรูเดียวกับ F2 ที่เพิ่ง
 * ปิดไป แค่แคบลง (เทส e2e จับได้ตอนเขียนครั้งแรก) · จึงต้องมีข้อที่ถูกอย่างน้อย
 * หนึ่งข้อเสมอด้วย
 *
 * ⚠️ นี่คือ **เกณฑ์ความคืบหน้า** ไม่ใช่หลักฐาน — ดู `isProofBearing()`
 */
export function passesLearnMode(correctCount: number, total: number): boolean {
  if (total === 0) return false
  return correctCount > 0 && total - correctCount <= LEARN_MODE_ALLOWED_WRONG
}

/**
 * node นี้เป็น "หลักฐาน" ที่ใบรับรองอ้างถึงได้ไหม
 *
 * กติกาที่ล็อกใน W0-3: **น้ำหนักของใบรับรองอยู่ที่ capstone ทั้งหมด**
 *
 * เหตุผลที่ `completed` ของบทปกติไม่นับ (ยอมรับตรงๆ ไม่ใช่แกล้งปิด): โหมด learn
 * บอกผลรายข้อ + คำอธิบาย และ retry ไม่จำกัด → บทปกติ 3 ข้อ × 4 ตัวเลือก ไล่ลอง
 * ไม่กี่รอบก็ผ่านโดยไม่ต้องรู้เนื้อหา · **นี่ไม่ใช่บั๊ก มันคือธรรมชาติของโหมดสอน**
 * จะปิดก็ต้องทิ้ง feedback ที่เป็นหัวใจของการเรียนไป
 */
export function isProofBearing(node: CourseNode): boolean {
  return node.kind === 'capstone'
}
