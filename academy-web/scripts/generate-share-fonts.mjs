#!/usr/bin/env node
// Regenerate src/lib/course-share-fonts.generated.ts from
// assets/fonts/noto-sans-thai/*.ttf.
//
// เหตุผลที่ต้อง inline: share/OG image render ตอน request บน Cloudflare Worker
// (workerd) ซึ่งไม่มี filesystem — node:fs.readFile ของ TTF ทำงานไม่ได้
// (production 2026-09-12: /courses/<slug>/share/* และ opengraph-image ตอบ 500
// หลัง candidate 73ac223 เปลี่ยนจาก build-time prerender เป็น request-time
// render). ฝังฟอนต์เป็น base64 module ต้นทางเดียว ใช้ได้ทั้ง Node และ workerd.
//
// ต้นฉบับความจริง (source of truth) คือไฟล์ .ttf ใน assets/fonts/noto-sans-thai
// หลังแก้/เปลี่ยนฟอนต์ให้รัน `node scripts/generate-share-fonts.mjs` แล้ว commit
// ทั้งคู่.

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fontDir = path.join(root, 'assets', 'fonts', 'noto-sans-thai')

function fontBase64(file) {
  const buffer = readFileSync(path.join(fontDir, file))
  if (buffer.length === 0) throw new Error(`font file is empty: ${file}`)
  return buffer.toString('base64')
}

const regular = fontBase64('NotoSansThai-Regular.ttf')
const bold = fontBase64('NotoSansThai-Bold.ttf')

const output = `// GENERATED by scripts/generate-share-fonts.mjs — do not edit by hand.
// Source of truth: assets/fonts/noto-sans-thai/*.ttf (Noto OFL license, see
// assets/fonts/noto-sans-thai/LICENSE). Inlined as base64 so share/OG image
// rendering works on workerd, which has no filesystem for node:fs reads.
export const NOTO_SANS_THAI_REGULAR_B64 = '${regular}'
export const NOTO_SANS_THAI_BOLD_B64 = '${bold}'
`

const target = path.join(root, 'src', 'lib', 'course-share-fonts.generated.ts')
writeFileSync(target, output)
console.log(`wrote ${path.relative(root, target)} (${regular.length + bold.length} base64 chars)`)
